    (0x1B6C64, 0x1B6CA1, "959f0d254000bf116d64ab7fb19d4dddb1e42b7b9e30360ac84b4318ac2d4717",
     "XMV bitreader/table helper; four arguments and ret 16"),
    (0x1B747C, 0x1B7514, "e54c1212a9d047c79d1b3b5b2f6e6e0cc41d308d9c28cd12215b38ab4ed7347d",
     "XMV eight-sample signed range predicate with an early four-sample reject; ret 36"),
