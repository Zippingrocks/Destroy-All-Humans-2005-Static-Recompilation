def image():
    data = (ROOT / "work/default.xbe").read_bytes()
    assert hashlib.sha256(data).hexdigest() == RETAIL_SHA, "unexpected retail XBE"
    base = struct.unpack_from("<I", data, 0x104)[0]
    count, table = struct.unpack_from("<II", data, 0x11C)
    sections = [struct.unpack_from("<9I", data, table - base + i * 56) for i in range(count)]

    def read(va, size):
        section = next(s for s in sections if s[1] <= va and va + size <= s[1] + s[4])
        offset = section[3] + va - section[1]
        return data[offset:offset + size]
    return data, read


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path)
    parser.add_argument("--evidence", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    _, read = image()
    decoder = Cs(CS_ARCH_X86, CS_MODE_32)
    records = []
    for start, end, expected, meaning in RANGES:
        raw = read(start, end - start)
        assert hashlib.sha256(raw).hexdigest() == expected
        instructions = list(decoder.disasm(raw, start))
        assert sum(i.size for i in instructions) == end - start
        records.append({"start": f"0x{start:08X}", "end": f"0x{end:08X}",
                        "bytesSha256": expected, "inferredDescription": meaning,
                        "instructions": [f"{i.address:08X} {i.bytes.hex()} {i.mnemonic} {i.op_str}".rstrip() for i in instructions]})
    artifacts = []
    for start, end, targets, explanation in (
        (0x1EC6D4, 0x1EC6F8, [0x1EC715, 0x1EC74C, 0x1EC762],
         "False branch edges from the XGRPH diagnostic string and preceding data; these are not observed callbacks."),
        (0x217640, 0x21767C, [0x21769D, 0x2176B9, 0x2176C7],
         "False branch edges from BINK copyright text decoded as x86; these are not observed callbacks."),
    ):
        raw = read(start, end - start)
        artifacts.append({"dataStart": f"0x{start:08X}", "dataEnd": f"0x{end:08X}",
                          "bytesSha256": hashlib.sha256(raw).hexdigest(),
                          "printableEvidence": raw.decode("ascii", errors="replace"),
                          "falseTargets": [f"0x{v:08X}" for v in targets], "explanation": explanation})
    evidence = json.dumps({"schema": 1, "source": "retail-xbe-only", "retailXbeSha256": RETAIL_SHA,
                           "restoredEntries": records, "unmodifiedDataArtifacts": artifacts}, indent=2) + "\n"
    for path, content in ((args.source, SOURCE), (args.evidence, evidence)):
        if path:
            if args.check:
                assert path.read_text(encoding="utf-8") == content, f"stale: {path}"
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    print("PASS: three retail entries byte-verified; six false data edges documented, not restored")


if __name__ == "__main__":
    main()
