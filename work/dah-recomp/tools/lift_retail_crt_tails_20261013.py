"""Reproduce seven retail CRT entries lost at SEH funclet boundaries.

Only retail bytes are used. These are address labels, not recovered symbols.
The x87 nonlocal-return tail and descriptor allocator loop entries are deferred.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

WORKSPACE = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(WORKSPACE / "third_party" / "xboxrecomp"))
from capstone import Cs, CS_ARCH_X86, CS_MODE_32
from tools.recomp.config import configure_from_xbe, va_to_file_offset
from tools.recomp.translator import FunctionTranslator

RANGES = (
    (0x13CA28, 0x13CA65, "allocation retry tail; inherited SEH frame"),
    (0x140DE6, 0x140E02, "invalid descriptor tail; errno and OS error reset"),
    (0x141081, 0x14109D, "invalid descriptor tail; errno and OS error reset"),
    (0x14254F, 0x1425CA, "stream close-all entry; live reachability unproven"),
    (0x14270F, 0x14272A, "stream flush-all completion tail; unlock and unwind"),
    (0x142C8F, 0x142CA3, "invalid descriptor tail; errno only"),
    (0x142DA3, 0x142DBF, "invalid descriptor tail; errno and OS error reset"),
)


def generate():
    xbe = WORKSPACE / "default.xbe"
    data = xbe.read_bytes()
    configure_from_xbe(str(xbe))
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    functions = {a: {"name": f"sub_{a:08X}", "end": b} for a, b, _ in RANGES}
    # A seven-entry database cannot auto-discover the SEH helper routines.
    # Explicit addresses preserve the caller's frame across prolog/epilog calls.
    translator = FunctionTranslator(data, functions, seh_prolog=0x13A120, seh_epilog=0x13A15B)
    source = ['/* Retail CRT entries, generated by lift_retail_crt_tails_20261013.py. */',
              '#define RECOMP_GENERATED_CODE', '#include "recomp_funcs.h"', '']
    evidence = []
    for start, end, purpose in RANGES:
        raw = data[va_to_file_offset(start):va_to_file_offset(start) + end - start]
        instructions = list(md.disasm(raw, start))
        assert sum(i.size for i in instructions) == end - start
        assert instructions[-1].address + instructions[-1].size == end
        assert instructions[-1].mnemonic == "ret"
        for i in instructions:
            if i.mnemonic.startswith("j"):
                assert start <= int(i.op_str, 16) < end, hex(i.address)
        code = translator.translate_function(start, functions[start])
        assert code and "TODO" not in code and "UNSUPPORTED" not in code
        source.append(code)
        evidence.append({"start": f"0x{start:08X}", "endExclusive": f"0x{end:08X}",
                         "bytes": len(raw), "instructions": len(instructions),
                         "sha256": hashlib.sha256(raw).hexdigest(), "purpose": purpose})
    record = {"schema": 1, "source": "retail-xbe-only",
              "retailXbeSha256": hashlib.sha256(data).hexdigest(), "entries": evidence,
              "scope": "Static body and isolated ABI validation; no claim of gameplay parity.",
              "sehHelpers": [
                  {"start": f"0x{a:08X}", "endExclusive": f"0x{b:08X}",
                   "sha256": hashlib.sha256(data[va_to_file_offset(a):va_to_file_offset(a) + b - a]).hexdigest()}
                  for a, b in ((0x13A120, 0x13A15B), (0x13A15B, 0x13A16C))],
              "deferred": [
                  {"address": "0x0013FBDC", "reason": "x87 extended constants and nonlocal guest return require separate validation"},
                  {"addresses": ["0x00142434", "0x00142450", "0x0014245C", "0x001424B3"],
                   "reason": "descriptor allocator tails loop into parent 0x00142352; restore coherent CFG rather than recursive tail calls"},
              ]}
    return "\n".join(source).rstrip() + "\n", json.dumps(record, indent=2) + "\n"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--source", type=Path)
    p.add_argument("--evidence", type=Path)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    source, evidence = generate()
    for path, content in ((args.source, source), (args.evidence, evidence)):
        if path:
            if args.check:
                assert path.read_text(encoding="utf-8") == content, f"Stale output: {path}"
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    if not args.source and not args.evidence:
        print(source)
    if args.check:
        print("PASS: seven CRT bodies and evidence reproduce from retail bytes")


if __name__ == "__main__":
    main()
